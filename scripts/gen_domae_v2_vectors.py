"""도매 v2 암호 계약의 공용 테스트 벡터 생성기 (TEST ONLY 키).

라이브러리(domae_mcp.v2)를 import 하지 않는다. 스펙 B1 인코딩 규약을 여기서 직접 바이트로 조립해
server(TypeScript)와 worker(Python) 구현이 각자 이 값을 재현하는지 확인하는 기준으로 쓴다.
사용: python scripts/gen_domae_v2_vectors.py tests/fixtures/domae_v2_vectors.json
"""
import base64
import hashlib
import json
import struct
import sys

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF


def lp(b: bytes) -> bytes:
    return struct.pack(">I", len(b)) + b


def u64(n: int) -> bytes:
    return struct.pack(">Q", n)


def b64(b: bytes) -> str:
    return base64.b64encode(b).decode()


def raw(priv) -> bytes:
    return priv.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)


# 고정 입력 (TEST ONLY)
CLIENT_PRIV = bytes(range(1, 33))
SERVER_PRIV = bytes(range(33, 65))
SIGN_PRIV = bytes(range(65, 97))
BEARER = "dmk_free_" + "0123456789abcdef" * 2
REQUEST_ID = bytes(range(100, 116))
SALT = bytes(range(120, 152))
DEVICE_ID_HEX = hashlib.sha256(b"test-device").hexdigest()
BUNDLE_HASH = hashlib.sha256(b"test-bundle").hexdigest()
RELEASE_SEQ = 42
PROTOCOL_VERSION = 2
RUNTIME_ID = {"implementation": "cpython", "python_version": "3.12.10", "magic": "cb0d0d0a",
              "artifact_kind": "marshal-code", "loader_abi": 1, "platform": "win_amd64"}
MODULES = {"alpha": b"\x00\x01test-module-alpha", "beta": b"test-module-beta\xff"}
IVS = {"alpha": bytes(range(160, 172)), "beta": bytes(range(172, 184))}
SIGNING_KEY_ID = "test-2026a"


def main(out_path: str) -> None:
    client = X25519PrivateKey.from_private_bytes(CLIENT_PRIV)
    server = X25519PrivateKey.from_private_bytes(SERVER_PRIV)
    signer = Ed25519PrivateKey.from_private_bytes(SIGN_PRIV)
    client_pub, server_pub = raw(client), raw(server)
    key_fp = hashlib.sha256(BEARER.encode("utf-8")).digest()
    device_id = bytes.fromhex(DEVICE_ID_HEX)
    rt = (lp(RUNTIME_ID["implementation"].encode()) + lp(RUNTIME_ID["python_version"].encode())
          + lp(bytes.fromhex(RUNTIME_ID["magic"])) + lp(RUNTIME_ID["artifact_kind"].encode())
          + lp(u64(RUNTIME_ID["loader_abi"])) + lp(RUNTIME_ID["platform"].encode()))
    info = (lp(b"domae-crawler-v2") + lp(u64(PROTOCOL_VERSION)) + lp(REQUEST_ID) + lp(client_pub)
            + lp(server_pub) + lp(key_fp) + lp(device_id) + lp(BUNDLE_HASH.encode())
            + lp(u64(RELEASE_SEQ)) + lp(rt))
    shared = server.exchange(X25519PrivateKey.from_private_bytes(CLIENT_PRIV).public_key())
    assert shared == client.exchange(server.public_key())
    session_key = HKDF(algorithm=hashes.SHA256(), length=32, salt=SALT, info=info).derive(shared)

    aad, modules = {}, {}
    for name, blob in MODULES.items():
        sha = hashlib.sha256(blob).digest()
        a = (lp(u64(PROTOCOL_VERSION)) + lp(REQUEST_ID) + lp(key_fp) + lp(device_id)
             + lp(BUNDLE_HASH.encode()) + lp(u64(RELEASE_SEQ)) + lp(rt) + lp(name.encode()) + lp(sha))
        out = AESGCM(session_key).encrypt(IVS[name], blob, a)
        aad[name] = a.hex()
        modules[name] = {"iv": b64(IVS[name]), "ct": b64(out[:-16]), "tag": b64(out[-16:]),
                         "artifact_sha256": b64(sha), "plain_b64": b64(blob)}

    signatures = {}
    payloads = {
        "domae-bundle-v2": json.dumps({"kind": "bundle", "release_seq": RELEASE_SEQ}, separators=(",", ":")),
        "domae-release-v1": json.dumps({"kind": "release", "note": "한글"}, ensure_ascii=False, separators=(",", ":")),
        "domae-revocation-v1": json.dumps({"kind": "revocation"}, separators=(",", ":")),
        "domae-update-v1": json.dumps({"kind": "update"}, separators=(",", ":")),
    }
    for domain, payload in payloads.items():
        digest = hashlib.sha256(lp(domain.encode()) + lp(SIGNING_KEY_ID.encode()) + lp(payload.encode("utf-8"))).digest()
        signatures[domain] = {"payload": payload, "signing_key_id": SIGNING_KEY_ID,
                              "digest_hex": digest.hex(), "signature": b64(signer.sign(digest))}

    vectors = {
        "_comment": "TEST ONLY keys. Generated by scripts/gen_domae_v2_vectors.py (worker repo). Do not edit by hand.",
        "inputs": {
            "client_priv_b64": b64(CLIENT_PRIV), "server_priv_b64": b64(SERVER_PRIV),
            "signing_priv_b64": b64(SIGN_PRIV), "signing_pub_b64": b64(raw(signer)),
            "signing_key_id": SIGNING_KEY_ID, "bearer": BEARER, "request_id_b64": b64(REQUEST_ID),
            "salt_b64": b64(SALT), "device_id_hex": DEVICE_ID_HEX, "bundle_hash": BUNDLE_HASH,
            "release_seq": RELEASE_SEQ, "protocol_version": PROTOCOL_VERSION, "runtime_id": RUNTIME_ID,
        },
        "key_fp": {"bearer": BEARER, "hex": key_fp.hex(), "b64": b64(key_fp)},
        "encoding": {"runtime_id_hex": rt.hex(), "kdf_info_hex": info.hex(), "aad": aad},
        "keys": {"client_pub_b64": b64(client_pub), "server_pub_b64": b64(server_pub),
                 "shared_hex": shared.hex(), "session_key_hex": session_key.hex()},
        "modules": modules,
        "signatures": signatures,
        "release_seq_cases": [
            {"value": 1, "valid": True}, {"value": 9007199254740991, "valid": True},
            {"value": 0, "valid": False}, {"value": -1, "valid": False},
            {"value": 1.5, "valid": False}, {"value": 9007199254740992, "valid": False},
            {"value": "5", "valid": False}, {"value": True, "valid": False}, {"value": None, "valid": False},
        ],
        "loader_abi_cases": [
            {"value": 0, "valid": True}, {"value": 9007199254740991, "valid": True},
            {"value": 9007199254740992, "valid": False}, {"value": -1, "valid": False},
            {"value": True, "valid": False}, {"value": 1.5, "valid": False},
        ],
    }
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(vectors, f, ensure_ascii=False, indent=2, sort_keys=True)
        f.write("\n")


if __name__ == "__main__":
    main(sys.argv[1])
